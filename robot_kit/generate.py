def sanity(cfg, warnings):
    mcu, W, rb = cfg["mcu"], cfg["wheels"], cfg["robot"]
    vmax = float(mcu["max_wheel_speed"])
    model = cfg["_model"]
    print(f"\n  robot '{rb['name']}': {rb['drive_type']}, {len(W)} wheels, "
          f"r = {rb['wheel_radius']} m, controller {cfg['nav']['controller']}")
    print("    #  name            x (m)    y (m)   counts/rev   edges/s at max speed")
    worst = 0.0
    for i, w in enumerate(W):
        edges = w["counts_per_rev"] * vmax / (2 * math.pi)
        worst = max(worst, edges)
        print(f"    {i}  {w['name']:<14} {w['x']:+.4f}  {w['y']:+.4f}   {w['counts_per_rev']:10.1f}"
              f"   {edges:10.0f}")
    top = vmax * float(rb["wheel_radius"])
    print(f"    wheel limit {vmax} rad/s = {top:.3f} m/s straight-line top speed")
    win = velocity_window(cfg)
    qn = velocity_quantum(cfg, win)
    print(f"    velocity resolution {qn:.4f} rad/s (window {win} tick(s) at "
          f"{mcu.get('control_hz', 100)} Hz)")
    if qn > 0.1:
        warnings.append(f"encoders are coarse: even over {win} ticks one count is {qn:.3f} rad/s. "
                        f"Use x4 decoding, a lower control_hz, or encoders on the motor shaft "
                        f"rather than the wheel (manual 4.3).")
    if cfg["nav"]["max_vx"] > top:
        warnings.append(f"nav.max_vx {cfg['nav']['max_vx']} m/s is above what the wheel limit "
                        f"allows ({top:.3f} m/s)")
    if cfg["teleop"]["max_linear"] > top:
        warnings.append(f"teleop.max_linear {cfg['teleop']['max_linear']} m/s is above the "
                        f"wheel limit's {top:.3f} m/s")
    if mcu["encoder_backend"] == "isr":
        total = worst * len(W)
        limit = 40000 if mcu.get("board") == "avr" else 300000
        if total > limit:
            warnings.append(f"ISR encoders: about {total:.0f} interrupts/s at top speed, more than "
                            f"this board handles comfortably (~{limit}). Lower max_wheel_speed, use "
                            f"encoder_decoding 2, or move to an ESP32 with pcnt (manual 4.2).")
    if mcu.get("board") == "avr" and int(mcu.get("baud", 0)) > 250000:
        warnings.append("AVR boards are unreliable above 250000 baud; use 115200")
    if any(k > 0 for k in mcu["kff"]):
        for i, w in enumerate(W):
            need = mcu["kff"][i] * vmax + mcu["kstat"][i]
            pmax = (1 << int(mcu.get("pwm_bits", 8))) - 1
            if need > 0.85 * pmax:
                warnings.append(f"wheel {w['name']}: feedforward alone needs {need:.0f} of {pmax} "
                                f"PWM at max_wheel_speed. Leave the PID ~15 % headroom (manual 9.8).")
    q = model.forward(model.inverse(0.1, 0.05, 0.3))
    print(f"    kinematics round trip (0.1, 0.05, 0.3) -> ({q[0]:.4f}, {q[1]:.4f}, {q[2]:.4f})")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=os.path.join(KIT, "robot_config.yaml"))
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    ap.add_argument("--out", default=KIT, help="root to write into (tests use a temp dir)")
    args = ap.parse_args()

    try:
        cfg = load_config(args.config)
    except (ConfigError, OSError) as e:
        print(f"\n  CONFIG ERROR: {e}\n")
        return 2
    warnings = []
    sanity(cfg, warnings)
    try:
        files = {
            "ros2/robot_base/config/robot.yaml": robot_params(cfg),
            "ros2/robot_base/config/nav2_params.yaml": nav2_params(cfg),
            "ros2/robot_base/config/slam_toolbox.yaml": slam_params(cfg),
            "ros2/robot_base/config/lidar.yaml": lidar_params(cfg),
            "ros2/robot_base/config/twist_mux.yaml": TWIST_MUX,
            "ros2/robot_base/config/kit.yaml": kit_yaml(cfg),
            "ros2/robot_base/urdf/robot.urdf": urdf(cfg),
            "firmware/robot_mcu/robot_config.h": firmware_header(cfg),
            "setup/generated/99-robot.rules": udev_rules(cfg, warnings),
            "setup/generated/robot.env": robot_env(cfg),
        }
    except ConfigError as e:
        print(f"\n  CONFIG ERROR: {e}\n")
        return 2

    for w in warnings:
        print(f"\n  WARNING: {w}")
    if args.check:
        print("\n  config OK (--check: nothing written)")
        return 0
    written = []
    for rel, text in files.items():
        write(os.path.join(args.out, rel), text, written)
    print("\n  wrote:")
    for p in written:
        print(f"    {p}")
    print("\n  next: rebuild the workspace (setup/04_workspace.sh) and reflash the MCU "
          "if robot_config.h changed.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())

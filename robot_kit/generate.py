def udev_line(dev, comment):
    vid, pid = str(dev.get("usb_vendor_id", "")).lower(), str(dev.get("usb_product_id", "")).lower()
    if not vid or not pid:
        return f"# {comment}: no usb_vendor_id / usb_product_id in robot_config.yaml\n"
    m = ['SUBSYSTEM=="tty"', f'ATTRS{{idVendor}}=="{vid}"', f'ATTRS{{idProduct}}=="{pid}"']
    if dev.get("usb_serial"):
        m.append(f'ATTRS{{serial}}=="{dev["usb_serial"]}"')
    if dev.get("usb_port_path"):
        m.append(f'KERNELS=="{dev["usb_port_path"]}"')
    m += [f'SYMLINK+="{dev["device_name"]}"', 'MODE="0666"']
    return f"# {comment}\n" + ", ".join(m) + "\n"


def identity(dev):
    return (str(dev.get("usb_vendor_id", "")).lower(), str(dev.get("usb_product_id", "")).lower(),
            dev.get("usb_serial") or "", dev.get("usb_port_path") or "")


def udev_rules(cfg, warnings):
    mcu, lid = cfg["mcu"], cfg["lidar"]
    out = "# GENERATED by robot_kit/generate.py. Install with setup/05_system.sh.\n"
    out += udev_line(mcu, f"microcontroller -> /dev/{mcu['device_name']}")
    if lid.get("model") not in ("none", None):
        out += udev_line(lid, f"LiDAR -> /dev/{lid['device_name']}")
        if identity(mcu) == identity(lid):
            warnings.append(
                "The MCU and the LiDAR have the SAME USB identity (VID, PID, serial, port path). "
                "udev cannot tell them apart. Fill usb_port_path for both (manual 8.2). "
                "This is exactly what bit NarrowAisleBot: two CP2102 adapters, same serial 0001.")
    return out



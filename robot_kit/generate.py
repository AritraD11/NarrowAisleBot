def nav2_params(cfg):
    nav, rb, lid = cfg["nav"], cfg["robot"], cfg["lidar"]
    holo = rb["drive_type"] in HOLONOMIC_TYPES
    max_vx, min_vx = float(nav["max_vx"]), float(nav.get("min_vx", -0.1))
    max_vy = float(nav.get("max_vy", 0.0)) if holo else 0.0
    max_wz = float(nav["max_wz"])
    acc = [float(a) for a in nav.get("accel", [0.3, 0.3, 0.8])]
    dec = [float(d) for d in nav.get("decel", [-0.5, -0.5, -1.0])]
    if not holo:
        acc[1], dec[1] = 0.0, 0.0
    fp = footprint(cfg, padded=True)
    fp_s = "[" + ", ".join(f"[{x:.3f}, {y:.3f}]" for x, y in fp) + "]"
    ctrl_hz = float(nav.get("controller_hz", 10.0))
    rng = min(float(lid.get("range_max", 10.0)), 8.0)
    v = dict(
        controller_hz=yflt(ctrl_hz), min_y_threshold="0.001" if holo else "0.5",
        goal_xy=yflt(nav["goal_xy_tolerance"]), goal_yaw=yflt(nav["goal_yaw_tolerance"]),
        max_vx=yflt(max_vx), min_vx=yflt(min_vx), max_vy=yflt(max_vy),
        min_vy=yflt(-max_vy), max_wz=yflt(max_wz), neg_max_wz=yflt(-max_wz),
        accel_vx=yflt(acc[0]), accel_vy=yflt(acc[1]), accel_wz=yflt(acc[2]),
        decel_vx=yflt(dec[0]), decel_vy=yflt(dec[1]), decel_wz=yflt(dec[2]),
        footprint=fp_s, inflation=yflt(nav["inflation_radius"]),
        resolution=yflt(cfg["slam"].get("resolution", 0.05)),
        raytrace_range=yflt(rng + 0.5), obstacle_range=yflt(rng),
        rot_vel=yflt(min(max_wz, 1.0)),
    )
    if nav["controller"] == "rpp":
        if holo:
            print("  ! nav.controller rpp on a holonomic base: it will never strafe")
        v["controller_block"] = RPP_BLOCK.substitute(v)
    else:
        steps = max(20, int(round(3.0 * ctrl_hz)))
        critics = ["ConstraintCritic", "CostCritic", "GoalCritic", "GoalAngleCritic",
                   "PathAlignCritic", "PathFollowCritic", "TwirlingCritic"]
        if not holo:
            critics[5:5] = ["PathAngleCritic", "PreferForwardCritic"]
        v["controller_block"] = MPPI_BLOCK.substitute(
            v, motion_model="Omni" if holo else "DiffDrive", batch=500, steps=steps,
            model_dt=yflt(1.0 / ctrl_hz), vy_std="0.2" if holo else "0.0",
            critics=", ".join(f'"{c}"' for c in critics),
            diff_only="false" if holo else "true")
    return NAV2.substitute(v)



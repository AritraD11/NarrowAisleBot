def yflt(v):
    """A float that YAML and ROS 2 both read as a DOUBLE. '10' would load as an
    integer, and rclpy/rclcpp refuse an integer for a parameter declared as a
    double (InvalidParameterTypeException), so there is always a '.' or 'e'."""
    v = float(v)
    s = f"{v:.6g}" if abs(v) >= 1e-4 or v == 0 else f"{v:.6e}"
    if not any(c in s for c in ".en"):          # n covers inf / nan
        s += ".0"
    return s


def ylist(vals):
    return "[" + ", ".join(yflt(v) for v in vals) + "]"


def slist(vals):
    return "[" + ", ".join(f'"{v}"' for v in vals) + "]"


def write(path, text, written):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as fh:
        fh.write(text)
    written.append(os.path.relpath(path, KIT))



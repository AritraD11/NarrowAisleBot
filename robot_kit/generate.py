def c_arr(vals, fmt="{:.6f}f"):
    return "{" + ", ".join(fmt.format(v) for v in vals) + "}"


def velocity_quantum(cfg, window):
    """rad/s that one encoder count represents, over `window` control ticks,
    on the coarsest encoder."""
    cpr = min(w["counts_per_rev"] for w in cfg["wheels"])
    dt = 1.0 / float(cfg["mcu"].get("control_hz", 100))
    return 2 * math.pi / (cpr * dt * window)


def velocity_window(cfg, target=0.05, cap=8):
    """Smallest window (in ticks) that gets the quantum to `target` rad/s,
    capped so the lag stays bounded."""
    return max(1, min(cap, math.ceil(velocity_quantum(cfg, 1) / target - 1e-9)))


def firmware_header(cfg):
    mcu, W, dtype = cfg["mcu"], cfg["wheels"], cfg["driver"]["type"]
    model = cfg["_model"]
    n = len(W)
